SELECT
    PES.NU_CNPJ_CPF,
    PES.NU_IE_ST,
    PES.CD_PESSOA,
    DRR.CD_DRR,
    PES.NU_CNPJ8,
    PES.NU_CNPJ,
    PES.NU_IE AS NU_IE,
    PES.CD_TIPO_PESSOA,
    PES.CD_SIST_ORIG,
    PES.CD_PARTICP,
    PES.CD_PESSOA_EMPR,
    PES.CD_PESSOA_ST,
    PES.NU_CPF,
    PES.IN_CNPJ_INSC_IE,
    PES.NM_PESSOA,
    PES.CD_CNAE_PRINCP,
    PES.CD_SRP,
    PES.CD_SRP_SIT_CAD,
    PES.CD_SRP_REGM_TRIB,
    PES.CD_SRP_CAT_REGM_TRIB,
    PES.CD_SRP_PRAZO_PAGTO,
    PES.CD_TSS,
    PES.CD_PESSOA_CONTAB,
    PES.CD_SIST_ORIG_CONTAB,
    PES.NU_FONE,
    PES.CD_TIPO_END,
    PES.DS_LOGR,
    PES.NU_LOGR,
    PES.DS_COMPL,
    PES.DS_BAIRRO,
    PES.NU_CEP,
    PES.NU_LAT,
    PES.NU_LONG,
    PES.CD_MUN_ANALIT,
    PES.CD_PESSOA_ARE,
    PES.CD_PESSOA_ARE_CENTR,
    PES.CD_PESSOA_DRR,
    PES.CD_UF,
    PES.CD_PESSOA_ORIG,
    PES.DS_TIPO_CLASSIF_PESSOA,
    PES.DT_REF_CAD,
    PES.DT_INI_ATIV,
    PES.DT_FIM_ATIV,
    PES.NM_FANTASIA,
    PES.DT_INI_EFD,
    PES.CD_SUB_SETOR_SIGEF
FROM P_ACCDB.DIM_PESSOA PES
INNER JOIN P_ACCDB.DIM_DRR DRR
    ON PES.CD_PESSOA_DRR = DRR.CD_PESSOA
WHERE
    DRR.CD_DRR = 17
    AND PES.NU_IE_ST IS NOT NULL
ORDER BY
    NU_CNPJ_CPF,
    NU_IE_ST,
    CD_PESSOA,
    CD_DRR;
